#!/usr/bin/env python3
"""Generate crates/afp-core/src/codepages/tables.rs.

Single-byte code page tables (byte -> Unicode scalar, or undefined) are
exported from Python's own codecs. CPython lacks the IBM EBCDIC pages 1047
and 1141; those two come from glibc iconv instead.

Usage: python3 tools/gen_codepages.py > crates/afp-core/src/codepages/tables.rs
"""

import codecs
import subprocess
import sys

UNDEFINED = 0xFFFF

# Multi-byte or special codecs handled by hand in Rust (or unsupported).
SKIP = {"cp932", "cp936", "cp949", "cp950", "cp1361", "cp65001", "cp367",
        "cp819"}

ICONV = {"cp1047": "IBM1047", "cp1141": "IBM1141"}


def python_codecs():
    found = []
    for n in range(70000):
        for cand in (f"cp{n}", f"cp{n:03d}"):
            try:
                codecs.lookup(cand)
            except LookupError:
                continue
            if cand not in SKIP and cand not in found:
                found.append(cand)
            break
    return found


def table_from_python(name):
    out = []
    for b in range(256):
        try:
            ch = bytes([b]).decode(name)
        except UnicodeDecodeError:
            out.append(UNDEFINED)
            continue
        if len(ch) != 1 or ord(ch) > 0xFFFE:
            raise SystemExit(f"{name}: byte {b:#x} decodes to {ch!r}")
        out.append(ord(ch))
    return out


def table_from_iconv(charset):
    raw = bytes(range(256))
    text = subprocess.run(
        ["iconv", "-f", charset, "-t", "UTF-32BE"],
        input=raw, capture_output=True, check=True,
    ).stdout
    if len(text) != 256 * 4:
        raise SystemExit(f"{charset}: iconv did not map every byte")
    return [int.from_bytes(text[i:i + 4], "big") for i in range(0, 1024, 4)]


def main():
    tables = {name: table_from_python(name) for name in python_codecs()}
    for name, charset in ICONV.items():
        tables[name] = table_from_iconv(charset)
    w = sys.stdout.write
    w("// @generated by tools/gen_codepages.py — do not edit by hand.\n")
    w("// Single-byte code pages: byte -> UTF-16 code unit, 0xFFFF = undefined.\n\n")
    w(f"pub const UNDEFINED: u16 = 0x{UNDEFINED:04X};\n\n")
    w("pub static TABLES: &[(&str, [u16; 256])] = &[\n")
    for name in sorted(tables, key=lambda n: int(n[2:])):
        w(f'    ("{name}", [\n')
        row = tables[name]
        for i in range(0, 256, 16):
            w("        " + ", ".join(f"0x{v:04X}" for v in row[i:i + 16]) + ",\n")
        w("    ]),\n")
    w("];\n")


if __name__ == "__main__":
    main()
